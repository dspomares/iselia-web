let currentLang = 'es';

function applyLang(lang) {
  const t = translations[lang];
  if (!t) return;
  currentLang = lang;

  // html lang + meta (per-page keys via data attrs, defaulting to the home page)
  document.documentElement.lang = lang;
  const titleKey = document.documentElement.dataset.i18nTitle || 'page-title';
  const descKey  = document.documentElement.dataset.i18nDesc  || 'meta-desc';
  if (t[titleKey] !== undefined) document.title = t[titleKey];
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc && t[descKey] !== undefined) metaDesc.setAttribute('content', t[descKey]);

  // mobile button aria
  const mobileBtn = document.getElementById('mobileToggle');
  if (mobileBtn) mobileBtn.setAttribute('aria-label', t['mobile-aria']);

  // aria del desplegable de idioma
  const langToggle = document.getElementById('langToggle');
  if (langToggle && t['lang-aria'] !== undefined) langToggle.setAttribute('aria-label', t['lang-aria']);

  // innerHTML elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (t[key] !== undefined) el.innerHTML = t[key];
  });

  // placeholder elements
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.dataset.i18nPh;
    if (t[key] !== undefined) el.placeholder = t[key];
  });

  // opcion marcada en el desplegable + codigo visible en el boton
  const langCode = document.getElementById('langCode');
  document.querySelectorAll('.lang-btn').forEach(btn => {
    const on = btn.dataset.lang === lang;
    btn.classList.toggle('active', on);
    btn.setAttribute('aria-current', on ? 'true' : 'false');
    if (on && langCode) langCode.textContent = btn.dataset.code || lang.toUpperCase();
  });

  // persist choice
  localStorage.setItem('iselia-lang', lang);
}

// El desplegable de idioma vive aqui y no en main.js a proposito: asi el
// selector entero (abrir, elegir, marcar) depende de un solo script.
function initLangMenu() {
  const wrap   = document.getElementById('langSwitcher');
  const toggle = document.getElementById('langToggle');
  if (!wrap || !toggle) return;

  const close = () => {
    wrap.classList.remove('open');
    toggle.setAttribute('aria-expanded', 'false');
  };

  toggle.addEventListener('click', e => {
    e.stopPropagation();
    const open = !wrap.classList.contains('open');
    wrap.classList.toggle('open', open);
    toggle.setAttribute('aria-expanded', open ? 'true' : 'false');
  });

  document.addEventListener('click', e => {
    if (!wrap.contains(e.target)) close();
  });
  document.addEventListener('keydown', e => {
    if (e.key === 'Escape' && wrap.classList.contains('open')) {
      close();
      toggle.focus();
    }
  });

  wrap.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', close);
  });
}

function initI18n() {
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => applyLang(btn.dataset.lang));
  });
  initLangMenu();

  // restore saved language (default es)
  const saved = localStorage.getItem('iselia-lang') || 'es';
  applyLang(saved);
}

// A consent platform can delay this script past DOMContentLoaded, and that event
// never fires again - so start straight away when the document is already parsed.
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initI18n);
} else {
  initI18n();
}
